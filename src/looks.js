const genderOk = (look, form) =>
  form.gender === 'Sin preferencia' || look.genders.includes(form.gender);

// Qué cumple un look respecto de lo que pidió el usuario
const criteria = (look, form) => ({
  style: genderOk(look, form),
  color: look.colors.includes(form.colorPalette),
  occasion: look.occasions.includes(form.occasion),
  garment: look.garmentTypes.includes(form.garmentType),
  fit: look.fits.includes(form.fitFeel),
});

// Look exacto: misma etapa, estilo, paleta y ocasión.
// La sensación y el tipo de prenda solo sirven para ordenar (primero la sensación).
const matches = (look, form) => {
  const c = criteria(look, form);
  return c.style && c.color && c.occasion;
};

const closeness = (look, form) => {
  const c = criteria(look, form);
  // La sensación pesa más que el tipo de prenda
  return (c.color ? 8 : 0) + (c.occasion ? 4 : 0) + (c.fit ? 2 : 0) + (c.garment ? 1 : 0);
};

const byCloseness = (form) => (a, b) => closeness(b, form) - closeness(a, form);

// Lista de lo que NO coincide, para la nota y para Gemini
const mismatchesOf = (look, form) => {
  const c = criteria(look, form);
  const list = [];
  if (!c.style) list.push(`estilo ${form.gender.toLowerCase()}`);
  if (!c.color) list.push(`paleta "${form.colorPalette}"`);
  if (!c.occasion) list.push(`ocasión "${form.occasion}"`);
  if (!c.garment) list.push(`prenda "${displayLabel(form.garmentType, form.gender)}"`);
  if (!c.fit) list.push(`sensación "${displayLabel(form.fitFeel, form.gender)}"`);
  return list;
};

// Textos en masculino cuando el estilo es Masculino (los valores internos no cambian)
export const MALE_LABELS = {
  'Top / Camiseta': 'Polera / Camiseta',
  'Cómoda y relajada': 'Cómodo y relajado',
  Ligera: 'Ligero',
  Estilizada: 'Estilizado',
  Definida: 'Definido',
};

export const displayLabel = (value, gender) =>
  gender === 'Masculino' ? MALE_LABELS[value] ?? value : value;

const joinEs = (items) =>
  items.length <= 1 ? items.join('') : `${items.slice(0, -1).join(', ')} y ${items[items.length - 1]}`;

export function getLook(form, variant = 0) {
  const sameStage = PHOTO_LOOKS.filter((look) => look.stages.includes(form.stage));
  if (!sameStage.length) return null;

  const exact = sameStage
    .filter((look) => matches(look, form))
    .sort(byCloseness(form));
  const close = sameStage
    .filter((look) => genderOk(look, form) && !exact.includes(look))
    .sort(byCloseness(form));
  const otherStyle = sameStage
    .filter((look) => !genderOk(look, form))
    .sort(byCloseness(form));

  const options = [...exact, ...close, ...otherStyle];
  const look = options[variant % options.length];
  const mismatches = mismatchesOf(look, form);

  let note = null;
  if (exact.includes(look) && mismatches.length) {
    note = `Coincide con tu etapa, estilo, paleta y ocasión, pero no con ${joinEs(mismatches)}.`;
  } else if (!exact.includes(look)) {
    note = `No tenemos un look exacto; este es el más cercano para tu etapa. No coincide en: ${joinEs(mismatches)}.`;
  }

  return { ...look, palette: PALETTES[look.colors[0]], note, mismatches };
}

// ---- Formulario guiado: solo se ofrecen opciones que llevan a un look exacto ----
// y que dejan al menos MIN_PALETTES paletas para elegir al final.
const MIN_PALETTES = 3;
const MINOR = ['Niño/a', 'Adolescente'];
const ALL_FITS = ['Cómoda y relajada', 'Ligera', 'Estilizada', 'Definida', 'Libre'];
const MINOR_FITS = ['Cómoda y relajada', 'Ligera', 'Libre'];
const ALL_GARMENTS = ['Pantalón amplio', 'Top / Camiseta', 'Vestido', 'Falda', 'Short', 'Chaqueta', 'Conjunto'];

const FIELD_MATCH = {
  occasion: (look, form) => look.occasions.includes(form.occasion),
  garmentType: (look, form) => look.garmentTypes.includes(form.garmentType),
  fitFeel: (look, form) => look.fits.includes(form.fitFeel),
  colorPalette: (look, form) => look.colors.includes(form.colorPalette),
};

const matchingLooks = (form, fields) =>
  PHOTO_LOOKS.filter((look) =>
    look.stages.includes(form.stage) &&
    genderOk(look, form) &&
    fields.every((f) => FIELD_MATCH[f](look, form))
  );

const paletteCount = (form) =>
  new Set(matchingLooks(form, ['occasion', 'garmentType', 'fitFeel']).flatMap((look) => look.colors)).size;

const fitOk = (form) => paletteCount(form) >= MIN_PALETTES;

const garmentOk = (form) =>
  (MINOR.includes(form.stage) ? MINOR_FITS : ALL_FITS).some((fitFeel) => fitOk({ ...form, fitFeel }));

const occasionOk = (form) =>
  ALL_GARMENTS
    .filter((g) => form.gender !== 'Masculino' || !['Vestido', 'Falda'].includes(g))
    .some((garmentType) => garmentOk({ ...form, garmentType }));

// ¿Se puede elegir este valor, considerando la etapa, el estilo y las respuestas anteriores?
export function isAvailable(form, field, value) {
  const test = { ...form, [field]: value };
  if (field === 'occasion') return occasionOk(test);
  if (field === 'garmentType') return garmentOk(test);
  if (field === 'fitFeel') return fitOk(test);
  return matchingLooks(test, ['occasion', 'garmentType', 'fitFeel', 'colorPalette']).length > 0;
}